"use client";

import React, { useState, useEffect, useMemo } from "react";
import {
  Brain,
  Sparkles,
  Zap,
  ShieldAlert,
  ShieldCheck,
  Copy,
  Trash2,
  Check,
  Dices,
  ChevronDown,
  Info,
} from "lucide-react";
import {
  generateSmartNegativePrompt,
  getRandomPromptArchetype,
  PROMPT_ARCHETYPES,
  brainstormPrompt,
  reformUserPrompt,
} from "@/app/lib/promptIntelligence";

interface PromptActionButtonsProps {
  prompt: string;
  onUpdatePrompt: (newPrompt: string) => void;
  negativePrompt?: string;
  onUpdateNegativePrompt?: (newNegativePrompt: string) => void;
  onEnhance?: () => Promise<void> | void;
  isEnhancing?: boolean;
  isNegativeBar?: boolean;
  className?: string;
  showToast?: (msg: string, type?: "success" | "error" | "info") => void;
}

const safeSessionGet = (key: string): string => {
  if (typeof window !== "undefined") {
    try {
      return sessionStorage.getItem(key) || "";
    } catch {
      return "";
    }
  }
  return "";
};

const safeSessionSet = (key: string, val: string) => {
  if (typeof window !== "undefined") {
    try {
      sessionStorage.setItem(key, val);
    } catch {}
  }
};

export default function PromptActionButtons({
  prompt,
  onUpdatePrompt,
  negativePrompt,
  onUpdateNegativePrompt,
  onEnhance,
  isEnhancing = false,
  isNegativeBar = false,
  className = "",
  showToast,
}: PromptActionButtonsProps) {
  const [copied, setCopied] = useState(false);
  const [isBrainstorming, setIsBrainstorming] = useState(false);
  const [isEnhancingLocal, setIsEnhancingLocal] = useState(false);
  const [isGeneratingNegative, setIsGeneratingNegative] = useState(false);
  const [showArchetypesDropdown, setShowArchetypesDropdown] = useState(false);
  const [negativeInsight, setNegativeInsight] = useState<string | null>(null);

  // Persistent tracking across component instances via sessionStorage & local state
  const [lastBrainstormedPrompt, setLastBrainstormedPrompt] = useState<string>(() =>
    safeSessionGet("sentinel_last_brainstormed")
  );
  const [lastEnhancedPrompt, setLastEnhancedPrompt] = useState<string>(() =>
    safeSessionGet("sentinel_last_enhanced")
  );
  const [lastNegativePositivePrompt, setLastNegativePositivePrompt] = useState<string>(() =>
    safeSessionGet("sentinel_last_neg_pos")
  );

  // Synchronize from session storage on mount
  useEffect(() => {
    const bs = safeSessionGet("sentinel_last_brainstormed");
    if (bs && bs !== lastBrainstormedPrompt) setLastBrainstormedPrompt(bs);
    const enh = safeSessionGet("sentinel_last_enhanced");
    if (enh && enh !== lastEnhancedPrompt) setLastEnhancedPrompt(enh);
    const neg = safeSessionGet("sentinel_last_neg_pos");
    if (neg && neg !== lastNegativePositivePrompt) setLastNegativePositivePrompt(neg);
  }, []);

  const cleanPrompt = (prompt || "").trim();
  const lowerPrompt = cleanPrompt.toLowerCase();
  const lowerLastBrainstormed = (lastBrainstormedPrompt || "").trim().toLowerCase();
  const lowerLastEnhanced = (lastEnhancedPrompt || "").trim().toLowerCase();
  const lowerLastNegativePos = (lastNegativePositivePrompt || "").trim().toLowerCase();

  // 1. Is the current text pane identical to what was generated by Brain-Storm?
  const isCurrentPromptBrainstormed = useMemo(() => {
    if (!cleanPrompt || !lowerLastBrainstormed) return false;
    return lowerPrompt === lowerLastBrainstormed;
  }, [cleanPrompt, lowerPrompt, lowerLastBrainstormed]);

  // 2. Is the current text pane identical to what was generated by Prompt Enhance?
  const isCurrentPromptEnhanced = useMemo(() => {
    if (!cleanPrompt || !lowerLastEnhanced) return false;
    return lowerPrompt === lowerLastEnhanced;
  }, [cleanPrompt, lowerPrompt, lowerLastEnhanced]);

  // 3. Is the negative prompt currently in sync with the positive prompt?
  // Note: AUTO-RESETS to false as soon as positive prompt changes!
  const isNegativePromptSynced = useMemo(() => {
    if (!cleanPrompt || !lowerLastNegativePos) return false;
    return lowerPrompt === lowerLastNegativePos;
  }, [cleanPrompt, lowerPrompt, lowerLastNegativePos]);

  // Check word count to allow short seed topic (e.g. "cyberpunk car") or empty pane
  const wordCount = cleanPrompt ? cleanPrompt.split(/\s+/).length : 0;
  const isSeedTopic = wordCount > 0 && wordCount <= 4 && cleanPrompt.length <= 35;
  const isPaneEmpty = !cleanPrompt;

  const isAnyProcessing = isBrainstorming || isEnhancing || isEnhancingLocal || isGeneratingNegative;

  // ─── Brain-Storm Button State ───
  // Active only when text pane is empty OR has a short 1-4 word seed topic,
  // AND is not already generated by Brain-Storm or Prompt Enhance.
  // Otherwise flat grey non-functional.
  const isBrainstormActive =
    !isAnyProcessing &&
    (isPaneEmpty || isSeedTopic) &&
    !isCurrentPromptBrainstormed &&
    !isCurrentPromptEnhanced;

  // ─── Prompt Enhance Button State ───
  // Re-forms casual, improper, or imaginative text into a balanced professional prompt.
  // STRICT RULE: Cannot enhance text generated by Brain-Storm (already professional).
  // Cannot re-enhance identical enhanced text (prevents multiple tapping / duplicate paste).
  const isEnhanceActive =
    !isAnyProcessing &&
    !isPaneEmpty &&
    !isCurrentPromptBrainstormed &&
    !isCurrentPromptEnhanced;

  // ─── Smart Negative Button State ───
  // Active when positive prompt has text and is not already synced.
  // Auto-resets as soon as positive prompt changes!
  const isNegativeActive =
    !isAnyProcessing &&
    !isPaneEmpty &&
    !isNegativePromptSynced;

  // ─────────────────────────────────────────────────────────────
  // 1. Brain-Storm Execution
  // ─────────────────────────────────────────────────────────────
  const handleBrainstorm = async () => {
    if (!isBrainstormActive) return;
    setIsBrainstorming(true);

    try {
      const activeCopilot =
        typeof window !== "undefined"
          ? localStorage.getItem("sentinel_active_copilot") || "mistral"
          : "mistral";

      const res = await fetch("/api/sentinel/enhance", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          prompt: cleanPrompt,
          provider: activeCopilot,
          mode: "brainstorm",
        }),
      });

      let resultingPrompt = "";
      let resultingNegative = "";

      if (res.ok) {
        const data = await res.json();
        resultingPrompt = data.enhancedPrompt;
        resultingNegative = data.suggestedNegative || "";
      }

      // Offline deterministic fallback if needed
      if (!resultingPrompt) {
        const bsFallback = brainstormPrompt(cleanPrompt);
        resultingPrompt = bsFallback.prompt;
        resultingNegative = bsFallback.suggestedNegative;
      }

      if (resultingPrompt) {
        const trimmed = resultingPrompt.trim();
        onUpdatePrompt(trimmed);
        setLastBrainstormedPrompt(trimmed);
        safeSessionSet("sentinel_last_brainstormed", trimmed);

        if (onUpdateNegativePrompt && resultingNegative) {
          onUpdateNegativePrompt(resultingNegative);
          setLastNegativePositivePrompt(trimmed);
          safeSessionSet("sentinel_last_neg_pos", trimmed);
        }

        if (showToast) {
          showToast("🧠 Brain-Storm: Composed professional masterwork prompt!", "success");
        }
      }
    } catch (err) {
      const bsFallback = brainstormPrompt(cleanPrompt);
      const trimmed = bsFallback.prompt.trim();
      onUpdatePrompt(trimmed);
      setLastBrainstormedPrompt(trimmed);
      safeSessionSet("sentinel_last_brainstormed", trimmed);

      if (onUpdateNegativePrompt && bsFallback.suggestedNegative) {
        onUpdateNegativePrompt(bsFallback.suggestedNegative);
        setLastNegativePositivePrompt(trimmed);
        safeSessionSet("sentinel_last_neg_pos", trimmed);
      }

      if (showToast) {
        showToast("🧠 Brain-Storm: Composed professional masterwork prompt!", "success");
      }
    } finally {
      setIsBrainstorming(false);
    }
  };

  // ─────────────────────────────────────────────────────────────
  // 2. Prompt Enhance Execution
  // ─────────────────────────────────────────────────────────────
  const handleEnhance = async () => {
    if (!isEnhanceActive) return;

    if (onEnhance) {
      try {
        await onEnhance();
        setLastEnhancedPrompt(cleanPrompt);
        safeSessionSet("sentinel_last_enhanced", cleanPrompt);
      } catch (e) {
        console.warn("Parent onEnhance error:", e);
      }
      return;
    }

    setIsEnhancingLocal(true);
    try {
      const activeCopilot =
        typeof window !== "undefined"
          ? localStorage.getItem("sentinel_active_copilot") || "mistral"
          : "mistral";

      const res = await fetch("/api/sentinel/enhance", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          prompt: cleanPrompt,
          provider: activeCopilot,
          mode: "enhance",
        }),
      });

      let reformed = "";
      if (res.ok) {
        const data = await res.json();
        reformed = data.enhancedPrompt;
      }

      if (!reformed) {
        reformed = reformUserPrompt(cleanPrompt);
      }

      if (reformed) {
        const trimmed = reformed.trim();
        onUpdatePrompt(trimmed);
        setLastEnhancedPrompt(trimmed);
        safeSessionSet("sentinel_last_enhanced", trimmed);

        if (showToast) {
          showToast("⚡ Prompt Enhance: Reformed into balanced professional tone!", "success");
        }
      }
    } catch (err) {
      const reformed = reformUserPrompt(cleanPrompt);
      const trimmed = reformed.trim();
      onUpdatePrompt(trimmed);
      setLastEnhancedPrompt(trimmed);
      safeSessionSet("sentinel_last_enhanced", trimmed);
      if (showToast) {
        showToast("⚡ Prompt Enhance: Reformed into balanced professional tone!", "success");
      }
    } finally {
      setIsEnhancingLocal(false);
    }
  };

  // ─────────────────────────────────────────────────────────────
  // 3. Smart Negative Deduction Execution
  // ─────────────────────────────────────────────────────────────
  const handleSmartNegativeGeneration = async () => {
    if (!onUpdateNegativePrompt || !cleanPrompt || !isNegativeActive) return;

    setIsGeneratingNegative(true);
    try {
      const localResult = generateSmartNegativePrompt(cleanPrompt);
      const activeCopilot =
        typeof window !== "undefined"
          ? localStorage.getItem("sentinel_active_copilot") || "mistral"
          : "mistral";

      const res = await fetch("/api/sentinel/negative-prompt", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          prompt: cleanPrompt,
          provider: activeCopilot,
        }),
      });

      let finalNegatives = localResult.negativePrompt;
      let finalExplanation = localResult.explanation;

      if (res.ok) {
        const data = await res.json();
        if (data.negativePrompt) finalNegatives = data.negativePrompt;
        if (data.explanation) finalExplanation = data.explanation;
      }

      onUpdateNegativePrompt(finalNegatives);
      setLastNegativePositivePrompt(cleanPrompt);
      safeSessionSet("sentinel_last_neg_pos", cleanPrompt);
      setNegativeInsight(finalExplanation);

      if (showToast) {
        showToast("🛡️ Smart Negative: Unwanted styles excluded!", "success");
      }
    } catch (e) {
      const fallback = generateSmartNegativePrompt(cleanPrompt);
      onUpdateNegativePrompt(fallback.negativePrompt);
      setLastNegativePositivePrompt(cleanPrompt);
      safeSessionSet("sentinel_last_neg_pos", cleanPrompt);
      setNegativeInsight(fallback.explanation);
      if (showToast) {
        showToast("🛡️ Smart Negative: Unwanted styles excluded!", "success");
      }
    } finally {
      setIsGeneratingNegative(false);
      setTimeout(() => setNegativeInsight(null), 8000);
    }
  };

  // ─────────────────────────────────────────────────────────────
  // 4. Utility Handlers (Copy, Clear, Inspire)
  // ─────────────────────────────────────────────────────────────
  const handleCopy = async () => {
    const textToCopy = isNegativeBar ? (negativePrompt || "") : prompt;
    if (!textToCopy) return;
    try {
      await navigator.clipboard.writeText(textToCopy);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
      if (showToast) showToast("Copied to clipboard", "info");
    } catch (e) {
      console.warn("Clipboard copy error:", e);
    }
  };

  const handleClear = () => {
    if (isNegativeBar) {
      if (onUpdateNegativePrompt) onUpdateNegativePrompt("");
      setLastNegativePositivePrompt("");
      safeSessionSet("sentinel_last_neg_pos", "");
    } else {
      onUpdatePrompt("");
      // Clearing positive pane clears lock so Brain-Storm is immediately ready!
    }
    if (showToast) showToast("Cleared", "info");
  };

  const handleRandomInspire = () => {
    const item = getRandomPromptArchetype();
    const trimmed = item.prompt.trim();
    onUpdatePrompt(trimmed);
    setLastBrainstormedPrompt(trimmed);
    safeSessionSet("sentinel_last_brainstormed", trimmed);

    if (onUpdateNegativePrompt && item.suggestedNegative) {
      onUpdateNegativePrompt(item.suggestedNegative);
      setLastNegativePositivePrompt(trimmed);
      safeSessionSet("sentinel_last_neg_pos", trimmed);
    }
    if (showToast) {
      showToast(`✨ Generated: ${item.name}`, "success");
    }
  };

  // Flat grey disabled styling
  const flatGreyButtonClass =
    "px-2.5 py-1 text-[11px] font-semibold text-slate-500 bg-slate-900/40 border border-slate-800/60 rounded-lg cursor-not-allowed opacity-50 select-none flex items-center gap-1 transition";

  // ─────────────────────────────────────────────────────────────
  // RENDER: NEGATIVE PROMPT BAR CONTROLS
  // ─────────────────────────────────────────────────────────────
  if (isNegativeBar) {
    return (
      <div className={`flex items-center gap-1.5 flex-wrap ${className}`}>
        {onUpdateNegativePrompt && (
          <button
            type="button"
            onClick={handleSmartNegativeGeneration}
            disabled={!isNegativeActive}
            className={
              isNegativeActive
                ? "group relative flex items-center gap-1 px-2.5 py-1 text-[11px] font-bold text-amber-300 hover:text-white bg-amber-950/70 hover:bg-amber-900/80 border border-amber-500/50 hover:border-amber-400 rounded-lg shadow-[0_0_10px_rgba(245,158,11,0.2)] hover:shadow-[0_0_14px_rgba(245,158,11,0.4)] transition active:scale-95"
                : flatGreyButtonClass
            }
            title={
              isNegativePromptSynced
                ? "🛡️ Negatives synced with current positive prompt • Edit prompt style to re-analyze"
                : !cleanPrompt
                ? "Enter positive prompt first to deduce negative styles"
                : "Smart Auto-Negative: Deduce exact negative styles (cartoon, anime, clay, silicon, plastic, doll, CGI) from positive prompt"
            }
          >
            {isNegativePromptSynced ? (
              <ShieldCheck className="w-3 h-3 text-emerald-400" />
            ) : (
              <ShieldAlert
                className={`w-3 h-3 ${
                  isGeneratingNegative ? "animate-spin text-amber-400" : "text-amber-400 group-hover:scale-110 transition-transform"
                }`}
              />
            )}
            <span>
              {isGeneratingNegative
                ? "Analyzing..."
                : isNegativePromptSynced
                ? "🛡️ Synced With Prompt"
                : "🛡️ Smart Auto-Negative"}
            </span>
          </button>
        )}

        <button
          type="button"
          onClick={handleCopy}
          disabled={!negativePrompt}
          className="flex items-center gap-1 px-2 py-1 text-[11px] font-semibold text-slate-400 hover:text-slate-200 bg-slate-900/80 hover:bg-slate-800 border border-slate-800 hover:border-slate-700 rounded-lg transition active:scale-95 disabled:opacity-30"
          title="Copy negative prompt"
        >
          {copied ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
          <span>{copied ? "Copied" : "Copy"}</span>
        </button>

        <button
          type="button"
          onClick={handleClear}
          disabled={!negativePrompt}
          className="p-1 text-slate-500 hover:text-rose-400 rounded-lg hover:bg-slate-900 transition disabled:opacity-30"
          title="Clear negative prompt"
        >
          <Trash2 className="w-3 h-3" />
        </button>

        {negativeInsight && (
          <span className="text-[10px] text-amber-300/90 font-mono animate-fadeIn flex items-center gap-1">
            <Info className="w-3 h-3 text-amber-400" />
            <span className="truncate max-w-[280px] sm:max-w-md">{negativeInsight}</span>
          </span>
        )}
      </div>
    );
  }

  // ─────────────────────────────────────────────────────────────
  // RENDER: POSITIVE PROMPT BAR CONTROLS
  // ─────────────────────────────────────────────────────────────
  return (
    <div className={`relative flex items-center gap-1.5 flex-wrap ${className}`}>
      {/* 1. Brain-Storm Prompt Writer Button */}
      <button
        type="button"
        onClick={handleBrainstorm}
        disabled={!isBrainstormActive}
        className={
          isBrainstormActive
            ? "group relative flex items-center gap-1 px-2.5 py-1 text-[11px] font-bold text-fuchsia-300 hover:text-white bg-fuchsia-950/70 hover:bg-fuchsia-900/80 border border-fuchsia-500/60 hover:border-fuchsia-400 rounded-lg shadow-[0_0_10px_rgba(217,70,239,0.25)] hover:shadow-[0_0_15px_rgba(217,70,239,0.45)] transition active:scale-95"
            : flatGreyButtonClass
        }
        title={
          isCurrentPromptBrainstormed
            ? "Brain-Storm already generated • Clear text pane to brainstorm fresh topic"
            : isCurrentPromptEnhanced
            ? "Prompt was already enhanced • Clear text pane to brainstorm fresh topic"
            : !isPaneEmpty && !isSeedTopic
            ? "Brain-Storm flat grey & disabled until text pane is empty or has a short 1-4 word seed topic"
            : "🧠 Brain-Storm: Composes a complete, professional masterwork prompt from a few words, a subject, or an empty pane"
        }
      >
        <Brain
          className={`w-3 h-3 ${
            isBrainstorming
              ? "animate-pulse text-fuchsia-400"
              : isBrainstormActive
              ? "text-fuchsia-400 group-hover:scale-110 transition-transform"
              : "text-slate-500"
          }`}
        />
        <span>{isBrainstorming ? "Brain-Storming..." : "🧠 Brain-Storm"}</span>
      </button>

      {/* 2. Prompt Enhance Button */}
      <button
        type="button"
        onClick={handleEnhance}
        disabled={!isEnhanceActive}
        className={
          isEnhanceActive
            ? "group relative flex items-center gap-1 px-2.5 py-1 text-[11px] font-bold text-cyan-300 hover:text-white bg-cyan-950/70 hover:bg-cyan-900/80 border border-cyan-500/60 hover:border-cyan-400 rounded-lg shadow-[0_0_10px_rgba(6,182,212,0.25)] hover:shadow-[0_0_15px_rgba(6,182,212,0.45)] transition active:scale-95"
            : flatGreyButtonClass
        }
        title={
          isCurrentPromptBrainstormed
            ? "Prompt Enhance disabled: Brain-Storm prompt is already written in a highly professional tone"
            : isCurrentPromptEnhanced
            ? "Prompt Enhance disabled: Already enhanced once • Type or paste fresh text to enhance"
            : isPaneEmpty
            ? "Prompt Enhance disabled: Enter draft prompt text to enhance"
            : "⚡ Prompt Enhance: Re-forms casual language, improper phrasing, or raw imagination into a balanced, professional prompt"
        }
      >
        <Zap
          className={`w-3 h-3 ${
            isEnhancing || isEnhancingLocal
              ? "animate-spin text-cyan-400"
              : isEnhanceActive
              ? "fill-cyan-400 text-cyan-400 group-hover:scale-110 transition-transform"
              : "text-slate-500"
          }`}
        />
        <span>{isEnhancing || isEnhancingLocal ? "Enhancing..." : "⚡ Prompt Enhance"}</span>
      </button>

      {/* 3. Master Prompt Presets Dropdown */}
      <div className="relative inline-block">
        <div className="flex items-center">
          <button
            type="button"
            onClick={handleRandomInspire}
            className="flex items-center gap-1 px-2 py-1 text-[11px] font-bold text-purple-300 hover:text-white bg-purple-950/70 hover:bg-purple-900/80 border border-purple-500/50 hover:border-purple-400 rounded-l-lg shadow-[0_0_10px_rgba(168,85,247,0.2)] hover:shadow-[0_0_14px_rgba(168,85,247,0.4)] transition active:scale-95"
            title="Randomly synthesize masterwork prompt + smart negative combo"
          >
            <Dices className="w-3 h-3 text-purple-400" />
            <span>🎲 Inspire</span>
          </button>
          <button
            type="button"
            onClick={() => setShowArchetypesDropdown((prev) => !prev)}
            className="px-1 py-1 text-purple-300 hover:text-white bg-purple-950/70 hover:bg-purple-900/80 border-y border-r border-purple-500/50 hover:border-purple-400 rounded-r-lg transition text-[10px]"
            title="Browse Master Prompt Archetypes"
          >
            <ChevronDown className="w-3 h-3" />
          </button>
        </div>

        {/* Archetypes Dropdown Menu */}
        {showArchetypesDropdown && (
          <div className="absolute left-0 mt-1 w-64 bg-slate-950 border border-purple-500/40 rounded-xl shadow-2xl p-2 z-50 animate-fadeIn backdrop-blur-xl">
            <div className="text-[10px] uppercase font-bold text-purple-300 tracking-wider px-2 py-1 border-b border-purple-500/20 flex items-center justify-between">
              <span>Master Prompt Presets</span>
              <button
                onClick={() => setShowArchetypesDropdown(false)}
                className="text-slate-500 hover:text-white"
              >
                ✕
              </button>
            </div>
            <div className="space-y-1 mt-1 max-h-56 overflow-y-auto">
              {PROMPT_ARCHETYPES.map((arch) => (
                <button
                  key={arch.id}
                  type="button"
                  onClick={() => {
                    const trimmed = arch.prompt.trim();
                    onUpdatePrompt(trimmed);
                    setLastBrainstormedPrompt(trimmed);
                    safeSessionSet("sentinel_last_brainstormed", trimmed);

                    if (onUpdateNegativePrompt && arch.suggestedNegative) {
                      onUpdateNegativePrompt(arch.suggestedNegative);
                      setLastNegativePositivePrompt(trimmed);
                      safeSessionSet("sentinel_last_neg_pos", trimmed);
                    }
                    setShowArchetypesDropdown(false);
                    if (showToast) showToast(`Loaded: ${arch.name}`, "success");
                  }}
                  className="w-full text-left px-2 py-1.5 rounded-lg hover:bg-purple-950/60 text-xs text-slate-200 transition group"
                >
                  <p className="font-semibold text-purple-200 group-hover:text-purple-300 truncate">
                    {arch.name}
                  </p>
                  <p className="text-[10px] text-slate-400 truncate">{arch.category}</p>
                </button>
              ))}
            </div>
          </div>
        )}
      </div>

      {/* 4. Smart Negative Generator from Positive Prompt */}
      {onUpdateNegativePrompt && (
        <button
          type="button"
          onClick={handleSmartNegativeGeneration}
          disabled={!isNegativeActive}
          className={
            isNegativeActive
              ? "flex items-center gap-1 px-2.5 py-1 text-[11px] font-bold text-amber-300 hover:text-white bg-amber-950/70 hover:bg-amber-900/80 border border-amber-500/50 hover:border-amber-400 rounded-lg shadow-[0_0_10px_rgba(245,158,11,0.2)] hover:shadow-[0_0_14px_rgba(245,158,11,0.4)] transition active:scale-95"
              : flatGreyButtonClass
          }
          title={
            isNegativePromptSynced
              ? "🛡️ Negatives synced with current positive prompt • Edit prompt style to re-analyze"
              : !cleanPrompt
              ? "Enter positive prompt first to deduce negative styles"
              : "Auto-Negative: Analyze positive prompt & populate negative prompt bar with unwanted styles to suppress"
          }
        >
          {isNegativePromptSynced ? (
            <ShieldCheck className="w-3 h-3 text-emerald-400" />
          ) : (
            <ShieldAlert
              className={`w-3 h-3 ${isGeneratingNegative ? "animate-spin text-amber-400" : "text-amber-400"}`}
            />
          )}
          <span>
            {isGeneratingNegative
              ? "Analyzing..."
              : isNegativePromptSynced
              ? "🛡️ Negatives Synced"
              : "🛡️ Auto-Negative"}
          </span>
        </button>
      )}

      {/* 5. Copy Prompt */}
      <button
        type="button"
        onClick={handleCopy}
        disabled={!cleanPrompt}
        className="flex items-center gap-1 px-2 py-1 text-[11px] font-semibold text-slate-400 hover:text-slate-200 bg-slate-900/80 hover:bg-slate-800 border border-slate-800 hover:border-slate-700 rounded-lg transition active:scale-95 disabled:opacity-30"
        title="Copy positive prompt"
      >
        {copied ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
        <span>{copied ? "Copied" : "Copy"}</span>
      </button>

      {/* 6. Clear Prompt */}
      <button
        type="button"
        onClick={handleClear}
        disabled={!cleanPrompt}
        className="p-1 text-slate-500 hover:text-rose-400 rounded-lg hover:bg-slate-900 transition disabled:opacity-30"
        title="Clear prompt (Unlocks Brain-Storm)"
      >
        <Trash2 className="w-3 h-3" />
      </button>
    </div>
  );
}
